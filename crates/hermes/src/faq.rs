/// تطبیق فوری — پرسش فارسی/انگلیسی → پاسخ ثابت (بدون توکن، بدون شبکه).
///
/// تطبیق روی متن lowercase شده انجام می‌شود؛ کلیدواژه‌های فارسی همان‌طور که
/// هستند جست‌وجو می‌شوند. اولین موضوعی که کلیدواژه‌اش حاضر باشد برنده است.
#[must_use]
pub fn match_instant_faq(query: &str) -> Option<&'static str> {
    let q = query.trim().to_lowercase();
    if q.is_empty() {
        return None;
    }
    FAQ_TOPICS
        .iter()
        .find(|t| t.keywords.iter().any(|kw| q.contains(&kw.to_lowercase())))
        .map(|t| t.answer)
}

/// کلید موضوع یافته‌شده — برای مسیریابی، لاگ و تست.
#[must_use]
pub fn match_instant_faq_key(query: &str) -> Option<&'static str> {
    let q = query.trim().to_lowercase();
    FAQ_TOPICS
        .iter()
        .find(|t| t.keywords.iter().any(|kw| q.contains(&kw.to_lowercase())))
        .map(|t| t.key)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// هر پرسش کلیدی مأموریت، بدون توکن جواب می‌گیرد.
    #[test]
    fn key_customer_questions_hit_instant_answers() {
        assert!(match_instant_faq_key("نحوه خرید و امنیت اسکرو چطوره؟").is_some());
        assert!(match_instant_faq_key("درصد پورسانت افیلیت و زیرمجموعه‌گیری چقدره؟").is_some());
        assert!(match_instant_faq_key("واریز و برداشت تتر و تون رو چطور انجام بدم؟").is_some());
        assert!(match_instant_faq_key("چطور با هوش مصنوعی هرمس محصول بسازم؟").is_some());
        assert!(match_instant_faq_key("پشتیبانی و داوری پارلمان کجاست؟").is_some());
    }

    /// پاسخ‌ها غیرخالی و چندخطی‌اند؛ ساختار خط اول + بولت رعایت می‌شود.
    #[test]
    fn answers_are_structured_and_nonempty() {
        for t in FAQ_TOPICS {
            assert!(!t.answer.trim().is_empty(), "{}", t.key);
            assert!(t.answer.contains('•'), "{} بدون بولت", t.key);
            assert!(t.answer.chars().count() > 120, "{} خیلی کوتاه", t.key);
            assert!(!t.keywords.is_empty(), "{} بدون کلیدواژه", t.key);
        }
        // حداقل ۵ موضوع کلیدی مأموریت
        assert!(FAQ_TOPICS.len() >= 5);
    }

    /// کلیدواژه‌های لاتین هم (case-insensitive) می‌گیرند؛ پرسش بی‌ربط → None.
    #[test]
    fn latin_keywords_and_misses() {
        assert!(match_instant_faq_key("how to pay with USDT?").is_some());
        assert!(match_instant_faq_key("ESCROW safe?").is_some());
        assert_eq!(match_instant_faq_key(""), None);
        assert_eq!(match_instant_faq_key("سلام خوبی؟"), None);
        assert_eq!(match_instant_faq_key("xyzabc"), None);
    }

    /// تطبیق قطعی است — همان ورودی، همان خروجی (بدون شانس).
    #[test]
    fn matching_is_deterministic() {
        let q = "چطور تتر واریز کنم؟";
        let a = match_instant_faq(q);
        assert_eq!(a, match_instant_faq(q));
        assert_eq!(match_instant_faq_key(q), Some("usdt_ton"));
    }
}
